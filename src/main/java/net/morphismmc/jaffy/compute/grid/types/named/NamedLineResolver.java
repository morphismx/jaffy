// plus the module-private free functions `split_area_edge_name`,
// `upsert_line_name_map` and `oz_line` (kept here as package-private statics).
//
// Type mappings:
//   `S: CheapCloneStr`                    -> `String` (DefaultCheapStr; GAP-017)
//   `StrHasher<S>`                        -> `String` (its Hash/Eq/Ord all defer
//                                          to the wrapped &str — String already
//                                          has exactly those semantics)
//   `LinePositions = SmallVec<[u32; 4]>`  -> `IntArrayList` (u32 -> int, GAP-014)
//   `NamedGridLinesMap<S>`                -> `Map<String, IntArrayList>`
//   `GridAreasMap<S>`                     -> `Map<String, AreaLines>`
//   `Vec<(u32, S)>` line-name pairs       -> `List<LineNamePair>` (record tuple)
//   `NonNamedGridPlacement`               -> `GenericGridPlacement<GridLine>`
//   u16/u32/i16/i32 -> int (GAP-014); assert! -> AssertionError (GAP-010);
