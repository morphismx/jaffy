/// Resolver that takes grid lines names and area names as input and can then be used to
/// resolve line names of grid placement properties into line numbers.
/// `pub(crate)` upstream -> public (callers cross package boundaries).
public final class NamedLineResolver {
    /// Map of row line names to line numbers. Each line name may correspond to multiple lines
    /// so we store an `IntArrayList` (`SmallVec` upstream)
    private final Map<String, IntArrayList> rowLines;
    /// Map of column line names to line numbers. Each line name may correspond to multiple lines
    /// so we store an `IntArrayList` (`SmallVec` upstream)
    private final Map<String, IntArrayList> columnLines;
    /// Map of area names to the lines of the area's edges
    private final Map<String, AreaLines> areas;
    /// Number of columns implied by grid area definitions
    private final int areaColumnCount;
    /// Number of rows implied by grid area definitions
    private final int areaRowCount;
    /// The number of explicit columns in the grid. This is an *input* to the `NamedLineResolver` and is
    /// used when computing the fallback line when a non-existent named line is specified.
    private int explicitColumnCount;
    /// The number of explicit rows in the grid. This is an *input* to the `NamedLineResolver` and is
    /// used when computing the fallback line when a non-existent named line is specified.
    private int explicitRowCount;
    /// The (1-indexed line number, name) pairs of every column line named in the track template,
    /// in source order (excludes the implicit names generated by `grid-template-areas`)
    private final List<LineNamePair> columnLineNamePairs;
    /// The (1-indexed line number, name) pairs of every row line named in the track template,
    /// in source order (excludes the implicit names generated by `grid-template-areas`)
    private final List<LineNamePair> rowLineNamePairs;

    /// `(u32, S)` tuple from `*_line_name_pairs`
    private record LineNamePair(int line, String name) {}

    /// `(&str, GridAreaEnd)` returned by `split_area_edge_name`
    record AreaEdgeName(String areaName, GridAreaEnd end) {}

    private NamedLineResolver(
            int areaColumnCount,
            int areaRowCount,
            int explicitColumnCount,
            int explicitRowCount,
            Map<String, IntArrayList> rowLines,
            Map<String, IntArrayList> columnLines,
            Map<String, AreaLines> areas,
            List<LineNamePair> columnLineNamePairs,
            List<LineNamePair> rowLineNamePairs) {
        this.areaColumnCount = areaColumnCount;
        this.areaRowCount = areaRowCount;
        this.explicitColumnCount = explicitColumnCount;
        this.explicitRowCount = explicitRowCount;
        this.rowLines = rowLines;
        this.columnLines = columnLines;
        this.areas = areas;
        this.columnLineNamePairs = columnLineNamePairs;
        this.rowLineNamePairs = rowLineNamePairs;
    }

    /// Split a line name of the form `<area-name>-start` or `<area-name>-end` into the area name and the edge
    /// `Option<(&str, GridAreaEnd)>` -> @Nullable AreaEdgeName
    static @Nullable AreaEdgeName splitAreaEdgeName(String name) {
        if (name.endsWith("-start")) {
            return new AreaEdgeName(name.substring(0, name.length() - "-start".length()), GridAreaEnd.START);
        }
        if (name.endsWith("-end")) {
            return new AreaEdgeName(name.substring(0, name.length() - "-end".length()), GridAreaEnd.END);
        }
        return null;
    }

    /// The named line maps store lines as 1-based "CSS Grid Line" numbers (which are always within the
    /// explicit grid). Convert one to OriginZero coordinates.
    static int ozLine(int line) {
        return line - 1;
    }

    /// Utility function to create or update an entry in a line name map
    ///
    /// `areas` must already contain the edges of the areas defined by `grid-template-areas`
    static void upsertLineNameMap(
            Map<String, IntArrayList> map, Map<String, AreaLines> areas, GridAreaAxis axis, String key, int value) {
        // A line named `foo-start` or `foo-end` is also an edge of the (implicitly) named area `foo`. Record it as such
        // if it is the first such line. If `foo` is also an area defined by `grid-template-areas`, then the line which
        // that area generated also has this name.
        int areaLine = 0;
        AreaEdgeName edge = splitAreaEdgeName(key);
        if (edge != null) {
            // The key is only created if the area is not already in the map
            AreaLines area = areas.get(edge.areaName());
            if (area == null) {
                area = AreaLines.DEFAULT;
            }
            int edgeLine = area.lineRaw(axis, edge.end());
            areaLine = edgeLine;
            areas.put(
                    edge.areaName(),
                    area.withLine(axis, edge.end(), edgeLine == 0 ? value : Integer.min(edgeLine, value)));
        }

        IntArrayList lines = map.get(key);
        if (lines != null) {
            lines.add(value);
        } else {
            // Until this entry is created, the only line that can have been recorded for this edge is the area's own
            IntArrayList fresh = new IntArrayList(2);
            if (areaLine != 0) {
                fresh.add(areaLine);
            }
            fresh.add(value);
            map.put(key, fresh);
        }
    }

    /// `<[u32]>::dedup` — removes consecutive repeated elements (input sorted).
    private static void dedup(IntArrayList lines) {
        if (lines.isEmpty()) {
            return;
        }
        int w = 1;
        for (int r = 1; r < lines.size(); r++) {
            if (lines.getInt(r) != lines.getInt(w - 1)) {
                lines.set(w++, lines.getInt(r));
            }
        }
        lines.size(w);
    }

    /// Create and initialise a new `NamedLineResolver`
    /// `pub(crate)` upstream; `::new` -> `newNamedLineResolver` per project convention.
    public static NamedLineResolver newNamedLineResolver(
            GridContainerStyle style, int columnAutoRepetitions, int rowAutoRepetitions) {
        Map<String, IntArrayList> columnLines = new HashMap<>();
        Map<String, IntArrayList> rowLines = new HashMap<>();
        Map<String, AreaLines> areas = new HashMap<>();

        List<LineNamePair> columnLineNamePairs = new ArrayList<>();
        List<LineNamePair> rowLineNamePairs = new ArrayList<>();

        // The size of the area template may be larger than the extents of the named areas
        // due to unnamed (`.`) cells, so it is taken from the style rather than being derived
        // from the areas themselves.
        int areaColumnCount = style.gridTemplateAreaColumnCount();
        int areaRowCount = style.gridTemplateAreaRowCount();
        Iterable<GridTemplateArea> areaIter = style.gridTemplateAreas();
        if (areaIter != null) {
            for (GridTemplateArea area : areaIter) {
                AreaLines lines = new AreaLines(area.rowStart(), area.rowEnd(), area.columnStart(), area.columnEnd());
                areas.put(area.name(), lines);
            }
        }

        int currentLine = 0;
        List<GenericGridTemplateComponent<GridTemplateRepetition>> columnTracks = style.gridTemplateColumns();
        if (columnTracks != null) {
            List<List<String>> columnLineNames = style.gridTemplateColumnNames();
            if (columnLineNames != null) {
                Iterator<GenericGridTemplateComponent<GridTemplateRepetition>> trackIter = columnTracks.iterator();
                for (List<String> lineNames : columnLineNames) {
                    currentLine += 1;
                    for (String lineName : lineNames) {
                        columnLineNamePairs.add(new LineNamePair(currentLine, lineName));
                        upsertLineNameMap(columnLines, areas, GridAreaAxis.COLUMN, lineName, currentLine);
                    }

                    if (trackIter.hasNext()
                            && trackIter.next()
                                    instanceof GenericGridTemplateComponent.Repeat<GridTemplateRepetition> comp) {
                        GridTemplateRepetition repeat = comp.repetition();
                        int repeatCount = switch (repeat.count()) {
                            case RepetitionCount.Count c -> c.count();
                            case RepetitionCount.AutoFill a -> columnAutoRepetitions;
                            case RepetitionCount.AutoFit a -> columnAutoRepetitions;
                        };

                        // Line name sets are positional: set `i` names the `i`th line of each
                        // repetition, and the final line name set of each repetition collapses
                        // with the first line name set of the following one. An empty list means
                        // the repetition's lines are unnamed; any other length must be exactly
                        // `track_count + 1` (one set per line, including both edge lines).
                        int lineNameSetCount = repeat.lineNames().size();
                        int linesPerRepetition = repeat.trackCount();
                        if (!(lineNameSetCount == 0 || lineNameSetCount == linesPerRepetition + 1)) {
                            throw new AssertionError(
                                    "grid template repetition must have no line name sets or exactly track count + 1"
                                            + " of them ("
                                            + linesPerRepetition + " tracks but " + lineNameSetCount
                                            + " line name sets)");
                        }

                        for (int r = 0; r < repeatCount; r++) {
                            int line = currentLine;
                            for (List<String> lineNameSet : repeat.lineNames()) {
                                for (String lineName : lineNameSet) {
                                    columnLineNamePairs.add(new LineNamePair(line, lineName));
                                    upsertLineNameMap(columnLines, areas, GridAreaAxis.COLUMN, lineName, line);
                                }
                                line++;
                            }
                            currentLine += linesPerRepetition;

                            // Names for lines beyond the maximum track limit are never resolvable:
                            // stop generating them (the explicit grid is clamped to MAX_GRID_TRACKS)
                            if (currentLine > Coordinates.MAX_GRID_TRACKS) {
                                break;
                            }
                        }
                        // Last line name set collapses with following line name set
                        if (repeatCount > 0) {
                            currentLine = Integer.max(0, currentLine - 1);
                        }
                    }
                }
            }
        }

        currentLine = 0;
        List<GenericGridTemplateComponent<GridTemplateRepetition>> rowTracks = style.gridTemplateRows();
        if (rowTracks != null) {
            List<List<String>> rowLineNames = style.gridTemplateRowNames();
            if (rowLineNames != null) {
                Iterator<GenericGridTemplateComponent<GridTemplateRepetition>> trackIter = rowTracks.iterator();
                for (List<String> lineNames : rowLineNames) {
                    currentLine += 1;
                    for (String lineName : lineNames) {
                        rowLineNamePairs.add(new LineNamePair(currentLine, lineName));
                        upsertLineNameMap(rowLines, areas, GridAreaAxis.ROW, lineName, currentLine);
                    }

                    if (trackIter.hasNext()
                            && trackIter.next()
                                    instanceof GenericGridTemplateComponent.Repeat<GridTemplateRepetition> comp) {
                        GridTemplateRepetition repeat = comp.repetition();
                        int repeatCount = switch (repeat.count()) {
                            case RepetitionCount.Count c -> c.count();
                            case RepetitionCount.AutoFill a -> rowAutoRepetitions;
                            case RepetitionCount.AutoFit a -> rowAutoRepetitions;
                        };

                        // Line name sets are positional: set `i` names the `i`th line of each
                        // repetition, and the final line name set of each repetition collapses
                        // with the first line name set of the following one. An empty list means
                        // the repetition's lines are unnamed; any other length must be exactly
                        // `track_count + 1` (one set per line, including both edge lines).
                        int lineNameSetCount = repeat.lineNames().size();
                        int linesPerRepetition = repeat.trackCount();
                        if (!(lineNameSetCount == 0 || lineNameSetCount == linesPerRepetition + 1)) {
                            throw new AssertionError(
                                    "grid template repetition must have no line name sets or exactly track count + 1"
                                            + " of them ("
                                            + linesPerRepetition + " tracks but " + lineNameSetCount
                                            + " line name sets)");
                        }

                        for (int r = 0; r < repeatCount; r++) {
                            int line = currentLine;
                            for (List<String> lineNameSet : repeat.lineNames()) {
                                for (String lineName : lineNameSet) {
                                    rowLineNamePairs.add(new LineNamePair(line, lineName));
                                    upsertLineNameMap(rowLines, areas, GridAreaAxis.ROW, lineName, line);
                                }
                                line++;
                            }
                            currentLine += linesPerRepetition;

                            // Names for lines beyond the maximum track limit are never resolvable:
                            // stop generating them (the explicit grid is clamped to MAX_GRID_TRACKS)
                            if (currentLine > Coordinates.MAX_GRID_TRACKS) {
                                break;
                            }
                        }
                        // Last line name set collapses with following line name set
                        if (repeatCount > 0) {
                            currentLine = Integer.max(0, currentLine - 1);
                        }
                    }
                }
            }
        }
        // Sort and dedup lines for each column name
        for (IntArrayList lines : columnLines.values()) {
            IntArrays.quickSort(lines.elements(), 0, lines.size());
            dedup(lines);
        }
        // Sort and dedup lines for each row name
        for (IntArrayList lines : rowLines.values()) {
            IntArrays.quickSort(lines.elements(), 0, lines.size());
            dedup(lines);
        }

        return new NamedLineResolver(
                areaColumnCount,
                areaRowCount,
                0 /* overwritten later */,
                0 /* overwritten later */,
                rowLines,
                columnLines,
                areas,
                columnLineNamePairs,
                rowLineNamePairs);
    }

    /// Build the per-line name groups of the explicit grid in the passed axis as a
    /// [`GridLineNames`], with `repeat()`s expanded. Only names given explicitly in the track
    /// template are included; the implicit `<name>-start`/`<name>-end` names generated by
    /// `grid-template-areas` are omitted (matching the resolved value of
    /// `grid-template-rows`/`grid-template-columns` in browsers) but remain resolvable for
    /// placement via [`GridLineNames::resolve_line_names`].
    ///
    /// Line indices are relative to the explicit grid (line 0 = start of the first explicit track).
    public GridLineNames detailedLineNames(AbsoluteAxis axis) {
        List<LineNamePair> pairs;
        int explicitTrackCount;
        switch (axis) {
            case HORIZONTAL -> {
                pairs = columnLineNamePairs;
                explicitTrackCount = explicitColumnCount;
            }
            case VERTICAL -> {
                pairs = rowLineNamePairs;
                explicitTrackCount = explicitRowCount;
            }
            default -> throw new IllegalStateException("unreachable");
        }

        if (pairs.isEmpty()) {
            return new GridLineNames();
        }

        // Stable sort by line number preserves the source order of names within each line
        List<LineNamePair> sortedPairs = new ArrayList<>(pairs);
        sortedPairs.sort(Comparator.comparingInt(LineNamePair::line));

        int lineCount = explicitTrackCount + 1;
        GridLineNames lineNames = GridLineNames.withCapacity(sortedPairs.size(), lineCount + 1);
        int i = 0;
        for (int line = 1; line <= lineCount; line++) {
            lineNames.startLine();
            while (i < sortedPairs.size()) {
                LineNamePair pair = sortedPairs.get(i);
                if (pair.line() != line) {
                    break;
                }
                i++;
                if (!lineNames.currentLineContains(pair.name())) {
                    lineNames.pushName(pair.name());
                }
            }
        }
        return lineNames;
    }

    /// Resolve named lines for both the `start` and `end` of a row-axis grid placement
    public Line<GenericGridPlacement<GridLine>> resolveRowNames(Line<GridPlacement> line) {
        return resolveLineNames(line, GridAreaAxis.ROW);
    }

    /// Resolve named lines for both the `start` and `end` of a column-axis grid placement
    public Line<GenericGridPlacement<GridLine>> resolveColumnNames(Line<GridPlacement> line) {
        return resolveLineNames(line, GridAreaAxis.COLUMN);
    }

    /// Resolve named lines for both the `start` and `end` of a grid placement
    public Line<GenericGridPlacement<GridLine>> resolveLineNames(Line<GridPlacement> line, GridAreaAxis axis) {
        Map<String, IntArrayList> lines;
        int explicitTrackCount;
        switch (axis) {
            case ROW -> {
                lines = rowLines;
                explicitTrackCount = explicitRowCount;
            }
            case COLUMN -> {
                lines = columnLines;
                explicitTrackCount = explicitColumnCount;
            }
            default -> throw new IllegalStateException("unreachable");
        }
        return new NamedLineResolverAxis(lines, areas, axis, explicitTrackCount).resolveLineNames(line);
    }

    /// Move the row and column line-name maps into the detailed grid information, and return the grid area map
    /// for the same purpose
    /// `GridAreasMap<S>` -> `Map<String, AreaLines>`
    public Map<String, AreaLines> populateDetailedLineResolvers(GridLineNames rows, GridLineNames columns) {
        rows.resolver = rowLines;
        columns.resolver = columnLines;
        return areas;
    }

    /// Get the number of columns defined by the grid areas
    public int areaColumnCount() {
        return areaColumnCount;
    }

    /// Get the number of rows defined by the grid areas
    public int areaRowCount() {
        return areaRowCount;
    }

    /// Set the number of columns in the explicit grid
    public void setExplicitColumnCount(int count) {
        this.explicitColumnCount = count;
    }

    /// Set the number of rows in the explicit grid
    public void setExplicitRowCount(int count) {
        this.explicitRowCount = count;
    }

    /// Manual `Debug` impl (writeln! sequence; map iteration order is unspecified
    /// in both Rust `HashMap` and Java `HashMap`).
    @Override
    public String toString() {
        StringBuilder f = new StringBuilder();
        f.append("Grid Areas (row-start / column-start / row-end / column-end):\n");
        for (Map.Entry<String, AreaLines> e : areas.entrySet()) {
            AreaLines area = e.getValue();
            f.append(e.getKey())
                    .append(": ")
                    .append(area.rowStart())
                    .append(" / ")
                    .append(area.columnStart())
                    .append(" / ")
                    .append(area.rowEnd())
                    .append(" / ")
                    .append(area.columnEnd())
                    .append('\n');
        }

        f.append("Grid Rows:\n");
        for (Map.Entry<String, IntArrayList> e : rowLines.entrySet()) {
            f.append(e.getKey()).append(": ");
            IntArrayList lines = e.getValue();
            for (int i = 0; i < lines.size(); i++) {
                f.append(lines.getInt(i)).append("  ");
            }
            f.append('\n');
        }

        f.append("Grid Columns:\n");
        for (Map.Entry<String, IntArrayList> e : columnLines.entrySet()) {
            f.append(e.getKey()).append(": ");
            IntArrayList lines = e.getValue();
            for (int i = 0; i < lines.size(); i++) {
                f.append(lines.getInt(i)).append("  ");
            }
            f.append('\n');
        }
        return f.toString();
    }
}
